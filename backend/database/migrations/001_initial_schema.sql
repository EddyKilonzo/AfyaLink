-- AfyaLink initial schema (PostgreSQL 15+)
-- Applied by `npm run db:migrate` (backend/scripts/db.mjs).
-- Kept in sync with the TypeORM entities in backend/src/database/entities.

-- ---------------------------------------------------------------------------
-- locations: administrative units a CHV serves (county > sub-county > ward > village)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS locations (
  id          INT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  county      VARCHAR(80)     NOT NULL,
  sub_county  VARCHAR(80)     NOT NULL,
  ward        VARCHAR(80)     NOT NULL,
  village     VARCHAR(120)    NULL,
  latitude    NUMERIC(9,6)    NULL,
  longitude   NUMERIC(9,6)    NULL,
  created_at  TIMESTAMPTZ(6)  NOT NULL DEFAULT NOW(),
  PRIMARY KEY (id),
  UNIQUE (county, sub_county, ward, village),
  CONSTRAINT chk_locations_lat CHECK (latitude IS NULL OR latitude BETWEEN -90 AND 90),
  CONSTRAINT chk_locations_lng CHECK (longitude IS NULL OR longitude BETWEEN -180 AND 180)
);

-- ---------------------------------------------------------------------------
-- users: CHVs and administrators. Role enum: CHV | ADMIN
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS users (
  id             UUID            NOT NULL,
  full_name      VARCHAR(120)    NOT NULL,
  email          VARCHAR(160)    NOT NULL,
  phone          VARCHAR(20)     NULL,
  password_hash  VARCHAR(100)    NOT NULL,
  role           VARCHAR(10)     NOT NULL DEFAULT 'CHV',
  location_id    INT             NULL,
  is_active      BOOLEAN         NOT NULL DEFAULT TRUE,
  last_login_at  TIMESTAMPTZ(6)  NULL,
  created_at     TIMESTAMPTZ(6)  NOT NULL DEFAULT NOW(),
  updated_at     TIMESTAMPTZ(6)  NOT NULL DEFAULT NOW(),
  PRIMARY KEY (id),
  UNIQUE (email),
  CONSTRAINT chk_users_role CHECK (role IN ('CHV','ADMIN')),
  CONSTRAINT fk_users_location FOREIGN KEY (location_id)
    REFERENCES locations (id) ON DELETE SET NULL ON UPDATE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_users_role ON users (role);

-- ---------------------------------------------------------------------------
-- health_reports: one community health observation.
-- id is a client-generated UUID v4, stable across offline sync retries.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS health_reports (
  id                 UUID          NOT NULL,
  chv_id             UUID          NOT NULL,
  location_id        INT           NULL,
  category           VARCHAR(30)   NOT NULL,
  condition_name     VARCHAR(120)  NOT NULL,
  severity           VARCHAR(10)   NOT NULL DEFAULT 'LOW',
  cases_count        INT           NOT NULL DEFAULT 1,
  age_group          VARCHAR(15)   NOT NULL DEFAULT 'MIXED',
  symptoms           JSONB         NULL,
  notes              TEXT          NULL,
  latitude           NUMERIC(9,6)  NULL,
  longitude          NUMERIC(9,6)  NULL,
  observed_at        TIMESTAMPTZ(6) NOT NULL,
  client_created_at  TIMESTAMPTZ(6) NOT NULL,
  status             VARCHAR(15)   NOT NULL DEFAULT 'SUBMITTED',
  received_at        TIMESTAMPTZ(6) NOT NULL DEFAULT NOW(),
  updated_at         TIMESTAMPTZ(6) NOT NULL DEFAULT NOW(),
  PRIMARY KEY (id),
  CONSTRAINT chk_reports_category CHECK (category IN ('DISEASE_CASE','MATERNAL_HEALTH','CHILD_HEALTH','NUTRITION','WATER_SANITATION','DEATH','OTHER')),
  CONSTRAINT chk_reports_severity CHECK (severity IN ('LOW','MODERATE','HIGH','CRITICAL')),
  CONSTRAINT chk_reports_cases CHECK (cases_count BETWEEN 1 AND 10000),
  CONSTRAINT chk_reports_age_group CHECK (age_group IN ('UNDER_5','AGE_5_17','AGE_18_59','AGE_60_PLUS','MIXED')),
  CONSTRAINT chk_reports_status CHECK (status IN ('SUBMITTED','REVIEWED','ACTIONED')),
  CONSTRAINT chk_reports_lat CHECK (latitude IS NULL OR latitude BETWEEN -90 AND 90),
  CONSTRAINT chk_reports_lng CHECK (longitude IS NULL OR longitude BETWEEN -180 AND 180),
  CONSTRAINT fk_reports_chv FOREIGN KEY (chv_id)
    REFERENCES users (id) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT fk_reports_location FOREIGN KEY (location_id)
    REFERENCES locations (id) ON DELETE SET NULL ON UPDATE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_reports_chv_observed ON health_reports (chv_id, observed_at);
CREATE INDEX IF NOT EXISTS idx_reports_category_observed ON health_reports (category, observed_at);
CREATE INDEX IF NOT EXISTS idx_reports_location ON health_reports (location_id);

-- ---------------------------------------------------------------------------
-- sync_logs: audit trail of sync batches (counts only, never report content).
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS sync_logs (
  id               BIGINT GENERATED ALWAYS AS IDENTITY NOT NULL,
  user_id          UUID          NOT NULL,
  device_id        VARCHAR(64)   NULL,
  received_count   INT           NOT NULL DEFAULT 0,
  created_count    INT           NOT NULL DEFAULT 0,
  duplicate_count  INT           NOT NULL DEFAULT 0,
  rejected_count   INT           NOT NULL DEFAULT 0,
  status           VARCHAR(10)   NOT NULL,
  started_at       TIMESTAMPTZ(6) NOT NULL,
  completed_at     TIMESTAMPTZ(6) NOT NULL,
  PRIMARY KEY (id),
  CONSTRAINT chk_sync_logs_status CHECK (status IN ('SUCCESS','PARTIAL','FAILED')),
  CONSTRAINT fk_sync_logs_user FOREIGN KEY (user_id)
    REFERENCES users (id) ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_sync_logs_user_started ON sync_logs (user_id, started_at);